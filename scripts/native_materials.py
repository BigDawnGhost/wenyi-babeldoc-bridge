"""Regenerate native dependency notices from the locked Cargo source graph.

Run with the bridge development environment. Downloads only the two license
files omitted from their crates.io archives, pinned to each crate's source commit.
The generated notices ship in wheels; source bundles include every locked crate.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
from pathlib import Path

import httpx
import toml

ROOT = Path(__file__).resolve().parents[1]
OMITTED_LICENSES = {
    "alloc-stdlib": (
        "https://raw.githubusercontent.com/dropbox/rust-alloc-no-stdlib/"
        "ae42d22078b98549e987d2f03d12df7b984fde47/LICENSE"
    ),
    "tiktoken-rs": (
        "https://raw.githubusercontent.com/zurawiki/tiktoken-rs/"
        "72a5a800651a1cea1ad609292446ba02c80e3bcd/LICENSE"
    ),
}


def source_archives() -> dict[str, tuple[str, str | None]]:
    """Return exact source URLs and registry checksums without invoking Cargo."""
    lock = toml.loads((ROOT / "rust/Cargo.lock").read_text(encoding="utf-8"))
    result = {}
    for package in lock["package"]:
        source = package.get("source", "")
        if source.startswith("registry+"):
            name, version = package["name"], package["version"]
            result[f"cargo/{name}-{version}.crate"] = (
                f"https://static.crates.io/crates/{name}/{name}-{version}.crate",
                package["checksum"],
            )
        elif source.startswith("git+https://github.com/funstory-ai/BabelDOC.git"):
            revision = source.rsplit("#", 1)[1]
            result[f"BabelDOC-{revision}.tar.gz"] = (
                f"https://codeload.github.com/funstory-ai/BabelDOC/tar.gz/{revision}",
                None,
            )
        elif source:
            raise ValueError(f"Unreviewed native dependency source: {source}")
    return result


def generate() -> None:
    metadata = json.loads(
        subprocess.check_output(
            [
                "cargo",
                "metadata",
                "--locked",
                "--format-version",
                "1",
                "--manifest-path",
                str(ROOT / "rust/Cargo.toml"),
            ],
            text=True,
        )
    )
    texts = {}
    catalog = []
    for package in sorted(metadata["packages"], key=lambda row: row["name"]):
        if not package["source"]:
            continue
        directory = Path(package["manifest_path"]).parent
        paths = sorted(
            path
            for path in directory.rglob("*")
            if path.is_file()
            and path.name.lower().startswith(
                ("license", "copying", "notice", "authors")
            )
        )
        # BabelDOC's internal crates inherit its repository-level AGPL license.
        if package["source"].startswith("git+"):
            parent = directory
            while not (parent / ".git").exists() and parent != parent.parent:
                parent = parent.parent
            paths.extend(path for path in parent.glob("LICENSE*") if path.is_file())
        notices = [
            (
                str(path.relative_to(directory))
                if path.is_relative_to(directory)
                else "upstream/LICENSE",
                path.read_text(encoding="utf-8"),
            )
            for path in paths
        ]
        if package["name"] in OMITTED_LICENSES:
            url = OMITTED_LICENSES[package["name"]]
            response = httpx.get(url, follow_redirects=True, timeout=60)
            response.raise_for_status()
            notices.append((url, response.text))
        if not notices:
            raise ValueError(f"Missing native notice: {package['name']}")
        catalog.extend(
            [
                f"## {package['name']} {package['version']}",
                f"License: {package['license'] or 'AGPL-3.0-only (BabelDOC repository)'}",
                f"Source: {package['source']}",
            ]
        )
        for name, text in notices:
            text = "\n".join(line.rstrip() for line in text.split("\n"))
            digest = hashlib.sha256(text.encode()).hexdigest()
            texts[digest] = text
            catalog.append(f"- {name}: notice `{digest}`")
    sections = [
        "# Native dependency notices",
        "Generated by `scripts/native_materials.py` from `rust/Cargo.lock`.",
        "Includes cross-platform and build dependencies; not every library is linked on every target.",
        *catalog,
    ]
    for digest, text in sorted(texts.items()):
        sections.extend([f"## Notice {digest}", "````text", text.rstrip(), "````"])
    (ROOT / "NATIVE_NOTICES.md").write_text(
        "\n\n".join(sections) + "\n", encoding="utf-8"
    )


if __name__ == "__main__":
    generate()
